@Composable
fun AppTheme(content: @Composable () -> Unit) {
    val dark = isSystemInDarkTheme()
    MaterialTheme(
        colorScheme = if (dark) DarkColors else LightColors,
        shapes = MaterialTheme.shapes.copy(
            medium = RoundedCornerShape(16.dp),
        ),
        content = content,
    )
}
